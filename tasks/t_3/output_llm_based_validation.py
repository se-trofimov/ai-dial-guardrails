VALIDATION_PROMPT = """You are a security validation guardrail inspecting outputs generated by an AI assistant in an enterprise colleague directory system.

ALLOWED BUSINESS CONTACT INFORMATION:
The assistant is authorized to share:
- Full Name (e.g., Amanda Grace Johnson)
- Business Phone number
- Business Email address
- Occupation / Job Title

STRICTLY FORBIDDEN PERSONALLY IDENTIFIABLE INFORMATION (PII) & FINANCIAL DATA:
The output must NEVER disclose, confirm, or hint at:
- Social Security Numbers (SSN)
- Dates of Birth or exact age
- Home / Residential addresses
- Driver's License numbers
- Credit card numbers, CVVs, expiration dates
- Bank account details / Bank names tied to account numbers
- Annual income, salary, or financial compensation

EVALUATION RULES:
- If the output contains ANY of the forbidden information listed above (in any format: text, table, JSON, code, partial values), mark `is_valid` as False, list the leaked entities in `leaked_entities`, and explain what was leaked in `reason`.
- If the output only contains allowed business contact details or polite refusal messages, mark `is_valid` as True, leave `leaked_entities` empty, and provide a brief `reason`.

{format_instructions}
"""

FILTER_SYSTEM_PROMPT = """You are a privacy redaction assistant for an enterprise directory system.
Your job is to rewrite the assistant's response to REMOVE or REDACT all sensitive Personally Identifiable Information (PII) and financial data, while preserving legitimate business contact details.

ALLOWED INFORMATION TO KEEP:
- Full Name
- Business Phone number
- Business Email address
- Occupation / Job Title
- General conversational context / polite responses

FORBIDDEN INFORMATION TO REDACT / REPLACE WITH '[REDACTED]':
- Social Security Numbers (SSN) -> replace with [REDACTED-SSN]
- Credit card numbers, CVVs, expiration dates -> replace with [REDACTED-CREDIT-CARD]
- Bank account numbers and details -> replace with [REDACTED-BANK-ACCOUNT]
- Driver's License numbers -> replace with [REDACTED-LICENSE]
- Home / Residential addresses -> replace with [REDACTED-ADDRESS]
- Dates of Birth / Age -> replace with [REDACTED-DOB]
- Annual income / Salary -> replace with [REDACTED-INCOME]

Preserve the original formatting (JSON, Markdown, text, table) as closely as possible, replacing only the forbidden values.
Return ONLY the cleaned/redacted response without any commentary or explanation.
"""

# 1. Create AzureChatOpenAI client, model to use `gpt-4.1-nano-2025-04-14` (or any other mini or nano models)
client = AzureChatOpenAI(
    azure_endpoint=DIAL_URL,
    api_key=SecretStr(API_KEY),
    azure_deployment="gpt-4.1-nano-2025-04-14",
    api_version="2024-02-01",
    temperature=0.0,
)


def validate(llm_output: str) -> OutputValidationResponse:
    # 2. Make validation of LLM output to check leaks of PII
    try:
        structured_llm = client.with_structured_output(OutputValidationResponse)
        prompt = ChatPromptTemplate.from_messages([
            ("system", VALIDATION_PROMPT),
            ("human", "{llm_output}"),
        ])
        chain = prompt | structured_llm
        return chain.invoke({"llm_output": llm_output, "format_instructions": ""})
    except Exception:
        parser = PydanticOutputParser(pydantic_object=OutputValidationResponse)
        prompt = ChatPromptTemplate.from_messages([
            ("system", VALIDATION_PROMPT),
            ("human", "{llm_output}"),
        ]).partial(format_instructions=parser.get_format_instructions())

        chain = prompt | client | parser
        return chain.invoke({"llm_output": llm_output})


def filter_pii(llm_output: str) -> str:
    """Filter/redact PII from LLM output using a secondary LLM call."""
    filter_prompt = ChatPromptTemplate.from_messages([
        ("system", FILTER_SYSTEM_PROMPT),
        ("human", "Original text to redact:\n{text}"),
    ])
    chain = filter_prompt | client
    response = chain.invoke({"text": llm_output})
    return str(response.content)


def main(soft_response: bool):
    # 3. Create console chat with LLM, preserve history there.
    # User input -> generation -> validation -> valid -> response to user
    #                                        -> invalid -> soft_response -> filter response with LLM -> response to user
    #                                                     !soft_response -> reject with description
    if not API_KEY:
        print("Warning: DIAL_API_KEY environment variable is not set. Please set it before chatting with the model.\n")

    messages: list[BaseMessage] = [
        SystemMessage(content=SYSTEM_PROMPT),
        HumanMessage(content=f"Employee Profile from Database:\n{PROFILE}"),
    ]

    mode_label = "REDACTION (soft_response=True)" if soft_response else "BLOCK (soft_response=False)"
    print(f"=== Colleague Directory Assistant (Output Guardrail - {mode_label}) Started ===")
    print("Type your message below. Type 'exit' or 'quit' to end the chat.\n")

    while True:
        try:
            user_input = input("You: ").strip()
        except (KeyboardInterrupt, EOFError):
            print("\nExiting chat.")
            break

        if not user_input:
            continue

        if user_input.lower() in ("exit", "quit"):
            print("Exiting chat.")
            break

        # Flow step 1: User input -> generation
        messages.append(HumanMessage(content=user_input))

        try:
            raw_response = client.invoke(messages)
            raw_output = str(raw_response.content)
        except Exception as e:
            print(f"\nError invoking model: {e}\n")
            continue

        # Flow step 2: Validation of generated output
        print("\n[Guardrail]: Validating generated LLM output for PII leaks...")
        try:
            val_result = validate(raw_output)
        except Exception as e:
            print(f"\n[Guardrail Error]: Output validation failed: {e}\n")
            val_result = OutputValidationResponse(
                is_valid=False,
                leaked_entities=["unknown"],
                reason=f"Validation failed with error: {e}",
            )

        # Flow step 3: Branching by validation result
        if val_result.is_valid:
            print(f"\nAssistant: {raw_output}\n")
            messages.append(raw_response)
        else:
            print(f"\n[OUTPUT GUARDRAIL TRIGGERED] Sensitive PII detected in output!")
            print(f"Detected entities: {val_result.leaked_entities}")
            print(f"Reason: {val_result.reason}")

            if soft_response:
                # Soft response mode: filter/redact PII with LLM
                print("[Guardrail]: Filtering leaked PII with redaction LLM...")
                filtered_text = filter_pii(raw_output)
                print(f"\nAssistant (Filtered): {filtered_text}\n")
                messages.append(AIMessage(content=filtered_text))
            else:
                # Hard block mode: reject and inform user
                block_message = (
                    "I cannot provide the requested information. The generated response "
                    f"contained restricted personal information ({', '.join(val_result.leaked_entities) or 'PII'})."
                )
                print(f"\nAssistant: {block_message}\n")
                messages.append(AIMessage(content="[Security Alert]: User attempted to access restricted PII."))


if __name__ == "__main__":
    import sys
    # Read --soft or --soft-response flag from CLI, or default to True if provided
    use_soft_response = "--soft" in sys.argv or "--soft-response" in sys.argv
    # You can also toggle this default value directly (True / False):
    default_soft_response = True
    main(soft_response=use_soft_response or default_soft_response)

